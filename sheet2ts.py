# Aseprite sheet + json -> hooks/sprite.ts, the band's character, as readable pixel art: a palette of
# one letter per colour and, per frame tag, each frame as rows of letters ('.' is clear). The module
# turns the rows into SVG rects when it loads.
# usage: python sheet2ts.py sheet.png sheet.json hooks/sprite.ts ["artwork credit line"]
# Tags the band uses: idle_front (required), idle_back, walk_front, sleep_front. Draw the front poses
# facing right; they are mirrored when the character heads left. A missing tag falls back to idle_front.
import json, string, sys
from collections import Counter
from PIL import Image

png, js, out = sys.argv[1:4]
credit = sys.argv[4] if len(sys.argv) > 4 else 'Sprite artwork: see LICENSE.'
sheet = Image.open(png).convert('RGBA'); px = sheet.load()
d = json.load(open(js, encoding='utf-8'))
frames = d['frames'] if isinstance(d['frames'], list) else list(d['frames'].values())
w = frames[0]['frame']['w']

def colour(c):
    return None if c[3] < 128 else '#%02x%02x%02x' % c[:3]

# letters by how often each colour is used, the commonest first
uses = Counter()
for f in frames:
    fx, fy = f['frame']['x'], f['frame']['y']
    for y in range(f['frame']['h']):
        for x in range(f['frame']['w']):
            c = colour(px[fx + x, fy + y])
            if c: uses[c] += 1
letters = string.ascii_lowercase + string.ascii_uppercase
if len(uses) > len(letters):
    sys.exit(f'{len(uses)} colours; at most {len(letters)} fit one letter each')
letter = {c: letters[i] for i, (c, _) in enumerate(uses.most_common())}

def rows(f):
    fx, fy = f['frame']['x'], f['frame']['y']
    return [''.join(letter.get(colour(px[fx + x, fy + y]), '.') for x in range(f['frame']['w'])) for y in range(f['frame']['h'])]

name = js.replace('\\', '/').split('/')[-1]
o = [
    f'// {credit}',
    f"// Generated by sheet2ts.py from {name}: one letter per colour, '.' for clear, one string per row.",
    '',
    f'export const SPRITE_SIZE = {w}',
    '',
    'const PALETTE: Record<string, string> = {',
    *[f"  {l}: '{c}'," for c, l in letter.items()],
    '}',
    '',
    'const ART: Record<string, { ms: number; frames: string[][] }> = {',
]
for t in d['meta']['frameTags']:
    fs = frames[t['from']:t['to'] + 1]
    o += [f"  {t['name']}: {{", f"    ms: {fs[0]['duration']},", '    frames: [']
    for f in fs:
        o += ['      [', *[f"        '{r}'," for r in rows(f)], '      ],']
    o += ['    ],', '  },']
NEW_TO_RECTS = r'''// a frame as SVG rects: a run of one colour along a row, grown taller while the same run repeats
// straight down the next rows (the pixels never overlap, so the order does not matter)
function toRects(frame: string[]): string {
  type Run = { x: number; y: number; w: number; h: number; c: string }
  const open = new Map<string, Run>(), done: Run[] = []
  frame.forEach((row, y) => {
    const seen = new Set<string>()
    for (const m of row.matchAll(/([^.])\1*/g)) {
      const key = `${m.index},${m[0].length},${m[1]}`, o = open.get(key)
      seen.add(key)
      if (o) o.h++
      else open.set(key, { x: m.index!, y, w: m[0].length, h: 1, c: PALETTE[m[1]!]! })
    }
    for (const [key, o] of open) if (!seen.has(key)) (done.push(o), open.delete(key))
  })
  return [...done, ...open.values()].map(o => `<rect x="${o.x}" y="${o.y}" width="${o.w}" height="${o.h}" fill="${o.c}"/>`).join('')
}'''
o += [
    '}',
    '',
    *NEW_TO_RECTS.split(chr(10)),
    '',
    'export const SPRITES: Record<string, { ms: number; frames: string[] }> = Object.fromEntries(',
    '  Object.entries(ART).map(([tag, { ms, frames }]) => [tag, { ms, frames: frames.map(toRects) }]),',
    ')',
]
open(out, 'w', encoding='utf-8').write('\n'.join(o) + '\n')
