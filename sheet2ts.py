# Aseprite sheet + json -> hooks/sprite.ts (the band's character): per frame tag, the frames as strings of 1x1 SVG rects
# (row runs) in the frame's own 0..w box, plus the exported ms per frame.
# usage: python sheet2ts.py sheet.png sheet.json hooks/sprite.ts ["artwork credit line"]
# Tags the band uses: idle_front (required), idle_back, walk_front, sleep_front, and optionally
# walk_side (drawn facing right, mirrored for leftward steps). A missing tag falls back to idle_front.
import json, sys
from PIL import Image

png, js, out = sys.argv[1:4]
credit = sys.argv[4] if len(sys.argv) > 4 else 'Sprite artwork: see LICENSE.'
sheet = Image.open(png).convert('RGBA'); px = sheet.load()
d = json.load(open(js, encoding='utf-8'))
frames = d['frames'] if isinstance(d['frames'], list) else list(d['frames'].values())

def rects(f):
    fx, fy, w, h = f['frame']['x'], f['frame']['y'], f['frame']['w'], f['frame']['h']
    o = []
    for y in range(h):
        x = 0
        while x < w:
            c = px[fx + x, fy + y]
            if c[3] < 128:
                x += 1; continue
            x0 = x
            while x < w and px[fx + x, fy + y] == c:
                x += 1
            o.append(f'<rect x="{x0}" y="{y}" width="{x - x0}" height="1" fill="#{c[0]:02x}{c[1]:02x}{c[2]:02x}"/>')
    return ''.join(o)

w = frames[0]['frame']['w']
lines = [
    f'// {credit}',
    f'// Generated by sheet2ts.py from {js.replace(chr(92), "/").split("/")[-1]}. Frames are {w}x{w}, ms per frame.',
    f'export const SPRITE_SIZE = {w}',
    'export const SPRITES: Record<string, { ms: number; frames: string[] }> = {',
]
for t in d['meta']['frameTags']:
    fs = frames[t['from']:t['to'] + 1]
    lines.append(f"  {t['name']}: {{ ms: {fs[0]['duration']}, frames: [")
    lines += [f"    '{rects(f)}'," for f in fs]
    lines.append('  ] },')
lines.append('}')
open(out, 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
